-- ============================================================
-- 1. CREATE SALES DATA TABLE
-- ============================================================

CREATE TABLE sales_data (
    order_id VARCHAR(20),
    order_date DATE,
    region VARCHAR(30),
    city VARCHAR(50),
    customer_id VARCHAR(20),
    category VARCHAR(50),
    product_name VARCHAR(100),
    quantity INTEGER,
    unit_price_inr NUMERIC(12,2),
    discount_percent NUMERIC(5,2),
    sales_inr NUMERIC(12,2),
    cost_inr NUMERIC(12,2),
    profit_inr NUMERIC(12,2),
    payment_method VARCHAR(30),
    order_status VARCHAR(20),
    delivery_minutes INTEGER,
    outlet_type VARCHAR(30)
);

-- View All Records
SELECT * FROM sales_data;

-- Check Total Number of Records
SELECT COUNT(*) FROM sales_data;


-- ============================================================
-- 2. OVERALL SALES PERFORMANCE
-- ============================================================

-- Business Questions:
-- 1. What are the total sales?
-- 2. What is the total number of orders?
-- 3. What is the total quantity sold?
-- 4. What is the total profit?
-- 5. What is the Average Order Value (AOV)?

SELECT
    SUM(sales_inr) AS total_Sales,
    COUNT(DISTINCT order_id) AS total_orders,
    SUM(quantity) AS total_quantity_sold,
    SUM(profit_inr) AS total_profit,
    ROUND (SUM(sales_inr) / COUNT(DISTINCT order_id),2) AS average_order_value
FROM sales_data;


-- ============================================================
-- 3. SALES PERFORMANCE BY REGION
-- ============================================================

-- Business Questions:
-- 1. What are the total sales in each region?
-- 2. How many orders were placed in each region?
-- 3. What is the total profit generated by each region?

SELECT
    region,
    SUM(sales_inr) AS total_sales,
    COUNT(DISTINCT order_id) AS total_order,
    SUM(profit_inr) AS total_profit
FROM sales_data
GROUP BY region;


-- ============================================================
-- 4. CATEGORY-WISE SALES ANALYSIS
-- ============================================================

-- Business Questions:
-- 1. What are the total sales for each category?
-- 2. What is the total profit generated by each category?
-- 3. What is the total quantity sold in each category?

SELECT
    category,
    SUM(sales_inr) AS total_sales,
    SUM(profit_inr) AS total_profit,
    SUM(quantity) AS total_quantity_sold
FROM sales_data
GROUP BY category;


-- ============================================================
-- 5. ORDER STATUS ANALYSIS
-- ============================================================

-- Business Questions:
-- 1. How many orders are there for each order status?
-- 2. What are the total sales for each order status?

SELECT
    order_status,
    COUNT(DISTINCT order_id) AS total_orders,
    SUM(sales_inr) AS total_sales
FROM sales_data
GROUP BY order_status;


-- ============================================================
-- 6. MONTHLY SALES TREND
-- ============================================================

-- Business Questions:
-- 1. What are the total sales for each month?
-- 2. How many orders were placed in each month?
-- 3. What is the monthly sales trend by year?

SELECT
    EXTRACT(YEARS FROM order_date) AS sales_Year,
    EXTRACT(MONTH FROM order_date) AS sales_months,
    SUM(sales_inr) AS total_slaes,
    COUNT(DISTINCT order_id) AS total_orders
FROM sales_data
GROUP BY
    EXTRACT(YEARS FROM order_date),
    EXTRACT(MONTH FROM order_date)
ORDER BY sales_year, sales_months;


-- ============================================================
-- 7. TOP 5 BEST-SELLING PRODUCTS
-- ============================================================

-- Business Question:
-- Which are the top 5 products generating the highest sales?

SELECT
    product_name,
    SUM(sales_inr) AS total_sales
FROM sales_data
GROUP BY product_name
ORDER BY total_sales DESC
LIMIT 5;


-- ============================================================
-- 8. CITY-WISE SALES PERFORMANCE
-- ============================================================

-- Business Questions:
-- 1. Which cities generate the highest sales?
-- 2. How many orders are placed in each city?
-- 3. What are the top 5 cities by sales?

SELECT
    city,
    SUM(sales_inr) AS total_sales,
    COUNT(DISTINCT order_id) AS total_order
FROM sales_data
GROUP BY city
ORDER BY total_sales DESC
LIMIT 5;


-- ============================================================
-- 9. PAYMENT METHOD ANALYSIS
-- ============================================================

-- Business Questions:
-- 1. What are the total sales by payment method?
-- 2. How many orders are placed using each payment method?
-- 3. What is the total profit by payment method?

SELECT
    payment_method,
    SUM(sales_inr) AS total_sales,
    COUNT(DISTINCT order_id) AS total_order,
    SUM(profit_inr) AS total_profit
FROM sales_data
GROUP BY payment_method
ORDER BY total_sales DESC;


-- ============================================================
-- 10. CUSTOMER-WISE SALES ANALYSIS
-- ============================================================

-- Business Questions:
-- 1. Who are the top 10 customers by total sales?
-- 2. How many orders has each customer placed?
-- 3. What is the total profit generated by each customer?

SELECT
    customer_id,
    COUNT(DISTINCT order_id) AS total_order,
    SUM(profit_inr) AS total_profit,
    SUM(sales_inr) AS total_sales
FROM sales_data
GROUP BY customer_id
ORDER BY total_sales DESC
LIMIT 10;


-- ============================================================
-- 11. HIGH-VALUE ORDER ANALYSIS
-- ============================================================

-- Business Question:
-- Which orders have a sales value greater than INR 5,000?

SELECT
    sales_inr,
    order_id,
    customer_id,
    order_date
FROM sales_data
WHERE sales_inr > 5000
ORDER BY sales_inr DESC;


-- ============================================================
-- 12. DELIVERED ORDERS ANALYSIS
-- ============================================================

-- Business Questions:
-- 1. What is the total profit from delivered orders?
-- 2. What are the total sales from delivered orders?
-- 3. What is the total quantity sold in delivered orders?

SELECT
    SUM(profit_inr) AS total_profit,
    SUM(sales_inr) AS total_sales,
    SUM(quantity) AS total_quantity_sold
FROM sales_data
WHERE order_status = 'Delivered';


-- ============================================================
-- 13. RETURNED ORDERS ANALYSIS
-- ============================================================

-- Business Questions:
-- 1. How many orders have been returned?
-- 2. What is the total profit from returned orders?
-- 3. What are the total sales of returned orders?

SELECT
    COUNT (*) AS total_count,
    SUM(profit_inr) AS total_profit,
    SUM(sales_inr) AS total_sales
FROM sales_data
WHERE order_status = 'Returned';


-- ============================================================
-- 14. PAYMENT METHOD ANALYSIS
-- ============================================================

-- Business Questions:
-- 1. What are the total sales by payment method?
-- 2. How many orders are placed using each payment method?

SELECT
    payment_method,
    SUM(sales_inr) AS total_sales,
    COUNT(DISTINCT order_id) AS total_order
FROM sales_data
GROUP BY payment_method;


-- ============================================================
-- 15. REGION-WISE PROFIT ANALYSIS
-- ============================================================

-- Business Questions:
-- 1. Which region generates the highest profit?
-- 2. What is the total profit generated by each region?

SELECT
    region,
    SUM(profit_inr) AS total_profit
FROM sales_data
GROUP BY region
ORDER BY total_profit DESC;


-- ============================================================
-- 16. CATEGORY-WISE SALES AND PROFIT ANALYSIS
-- ============================================================

-- Business Questions:
-- 1. What is the total profit generated by each category?
-- 2. What are the total sales for each category?
-- 3. What is the profit margin percentage for each category?

SELECT
    category,
    SUM(profit_inr) AS total_profit,
    SUM(sales_inr) AS total_sales,
    ROUND ((SUM ( profit_inr)/ SUM (sales_inr)) *100,2) AS profit_margin
FROM sales_data
GROUP BY category;


-- ============================================================
-- 17. MONTHLY SALES GROWTH ANALYSIS
-- ============================================================

-- Business Questions:
-- 1. What are the total sales for each month?
-- 2. How do sales vary across different months?

SELECT
    EXTRACT ( MONTH FROM order_date ) AS sales_month,
    SUM(sales_inr) AS total_sales
FROM sales_data
GROUP BY sales_month
ORDER BY sales_month;


-- ============================================================
-- 18. CUSTOMER REPEAT PURCHASE ANALYSIS
-- ============================================================

-- Business Questions:
-- 1. Which customers have placed more than 3 orders?
-- 2. What are their total sales?
-- 3. How many orders have these customers placed?

SELECT
    customer_id,
    SUM(sales_inr) AS total_sales,
    COUNT(DISTINCT order_id) AS total_order
FROM sales_data
GROUP BY customer_id
HAVING COUNT(DISTINCT order_id) > 3
ORDER BY total_order DESC;


-- ============================================================
-- 19. TOP-SELLING PRODUCTS ANALYSIS
-- ============================================================

-- Business Questions:
-- 1. Which products have the highest quantity sold?
-- 2. What are the total sales generated by each product?
-- 3. What are the top 5 products by quantity sold?

SELECT
    product_name,
    SUM(sales_inr) AS total_sales,
    SUM(quantity) AS total_quantity_sold
FROM sales_data
GROUP BY product_name
ORDER BY total_quantity_sold DESC
LIMIT 5;


-- ============================================================
-- 20. REGION-WISE AVERAGE PROFIT ANALYSIS
-- ============================================================

-- Business Questions:
-- 1. What is the average profit for each region?
-- 2. Which regions have an average profit below the overall average profit?
-- 3. What are the total sales generated by these regions?

SELECT
    region,
    ROUND(AVG(profit_inr),2) AS avg_profit,
    SUM(sales_inr) AS total_sales
FROM sales_data
GROUP BY region
HAVING AVG(profit_inr) <(SELECT AVG(profit_inr)
FROM sales_data)
ORDER BY avg_profit ASC;


-- ============================================================
-- 21. CATEGORY-WISE TOP PERFORMING PRODUCT
-- ============================================================

-- Business Questions:
-- 1. Which product generates the highest sales in each category?
-- 2. How can products be ranked within each category?
-- 3. Which products hold Rank 1 in their respective categories?

WITH product_sales AS (
    SELECT
        category,
        product_name,
        SUM(sales_inr) AS total_sales
    FROM sales_data
    GROUP BY category, product_name
),
ranked_products AS (
    SELECT
        category,
        product_name,
        total_sales,
        RANK() OVER (
            PARTITION BY category
            ORDER BY total_sales DESC
        ) AS product_rank
    FROM product_sales
)
SELECT *
FROM ranked_products
WHERE product_rank = 1
ORDER BY category;


